// The preview page's data (animations.html opens from disk, where module imports and fetch are blocked): the cat's rig
// from packages/cat/cat.json and the device's reference player and dots as one classic script.
//   node packages/cat/blender/preview_data.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const here = new URL('./', import.meta.url), repo = new URL('../../../', import.meta.url);
mkdirSync(new URL('anim/', here), { recursive: true });
const pkg = JSON.parse(readFileSync(new URL('packages/cat/cat.json', repo), 'utf8'));
writeFileSync(new URL('anim/cat-rig.js', here), `window.CAT_RIG = ${JSON.stringify(pkg.creature.rig)};\n`);
const strip = (s) => s.replace(/^import .*$/gm, '').replace(/^export (const|function|class) /gm, '$1 ');
const src = ['device/creatures/js/clip-player.js', 'device/creatures/js/clip-dots.js'].map((f) => strip(readFileSync(new URL(f, repo), 'utf8')));
writeFileSync(new URL('anim/clip-runtime.js', here),
  `// generated by preview_data.mjs from device/creatures/js/clip-player.js and clip-dots.js\n(() => {\n${src.join('\n')}\nwindow.ClipRuntime = { clipPlayer, clipDots, route };\n})();\n`);
console.log('wrote anim/cat-rig.js and anim/clip-runtime.js');
