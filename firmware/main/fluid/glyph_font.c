#include "glyph_font.h"

const char *GC_RAMP_ASCII = " .,:;!+=*xX#@";   /* 13 chars, dark → bright (glyphcss "ascii") */

/* 5x7 bitmaps (bit4 = leftmost column, row 0 = top) for ASCII 32..90: the ramp
 * glyphs, uppercase and digits. Lowercase is drawn as uppercase (except 'x', a
 * distinct ramp level). Most unused punctuation is blank; '?' and '!' are drawn
 * because reader text ends in them. Unknown chars → solid block. */
const uint8_t *gc_font5x7(char c) {
    static const uint8_t FONT[59][7] = {
        {0,0,0,0,0,0,0},{4,4,4,4,4,0,4},{0},{0x0a,0x0a,0x1f,0x0a,0x1f,0x0a,0x0a},{0},{0},{0},{0},
        {0},{0},{0,4,0x15,0x0e,0x15,4,0},{0,0,4,0x0e,4,0,0},{0,0,0,0,0,6,4},{0,0,0,0x0e,0,0,0},{0,0,0,0,0,6,6},{1,2,2,4,8,8,0x10},
        {0x0e,0x11,0x13,0x15,0x19,0x11,0x0e},{4,0x0c,4,4,4,4,0x0e},{0x0e,0x11,1,2,4,8,0x1f},{0x1f,2,4,2,1,0x11,0x0e},
        {2,6,0x0a,0x12,0x1f,2,2},{0x1f,0x10,0x1e,1,1,0x11,0x0e},{6,8,0x10,0x1e,0x11,0x11,0x0e},{0x1f,1,2,4,8,8,8},
        {0x0e,0x11,0x11,0x0e,0x11,0x11,0x0e},{0x0e,0x11,0x11,0x0f,1,2,0x0c},{0,6,6,0,6,6,0},{0,6,6,0,6,6,4},{0},{0,0,0x0e,0,0x0e,0,0},{0},{0x0e,0x11,1,2,4,0,4},
        {0x0e,0x11,0x17,0x15,0x17,0x10,0x0e},
        {0x0e,0x11,0x11,0x1f,0x11,0x11,0x11},{0x1e,0x11,0x11,0x1e,0x11,0x11,0x1e},{0x0e,0x11,0x10,0x10,0x10,0x11,0x0e},{0x1e,0x11,0x11,0x11,0x11,0x11,0x1e},
        {0x1f,0x10,0x10,0x1e,0x10,0x10,0x1f},{0x1f,0x10,0x10,0x1e,0x10,0x10,0x10},{0x0e,0x11,0x10,0x17,0x11,0x11,0x0f},{0x11,0x11,0x11,0x1f,0x11,0x11,0x11},
        {0x0e,4,4,4,4,4,0x0e},{7,2,2,2,2,0x12,0x0c},{0x11,0x12,0x14,0x18,0x14,0x12,0x11},{0x10,0x10,0x10,0x10,0x10,0x10,0x1f},
        {0x11,0x1b,0x15,0x15,0x11,0x11,0x11},{0x11,0x11,0x19,0x15,0x13,0x11,0x11},{0x0e,0x11,0x11,0x11,0x11,0x11,0x0e},{0x1e,0x11,0x11,0x1e,0x10,0x10,0x10},
        {0x0e,0x11,0x11,0x11,0x15,0x12,0x0d},{0x1e,0x11,0x11,0x1e,0x14,0x12,0x11},{0x0f,0x10,0x10,0x0e,1,1,0x1e},{0x1f,4,4,4,4,4,4},
        {0x11,0x11,0x11,0x11,0x11,0x11,0x0e},{0x11,0x11,0x11,0x11,0x11,0x0a,4},{0x11,0x11,0x11,0x15,0x15,0x1b,0x11},{0x11,0x11,0x0a,4,0x0a,0x11,0x11},
        {0x11,0x11,0x0a,4,4,4,4},{0x1f,1,2,4,8,0x10,0x1f},
    };
    static const uint8_t XLO[7]={0,0,0x11,0x0a,4,0x0a,0x11};   /* lowercase x — distinct ramp level */
    static const uint8_t FULL[7]={0x1f,0x1f,0x1f,0x1f,0x1f,0x1f,0x1f};
    if (c == 'x') return XLO;
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c >= 32 && c <= 90) return FONT[(int)c - 32];
    return FULL;
}
