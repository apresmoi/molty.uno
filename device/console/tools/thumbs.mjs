// Pre-render the Molty picker thumbnails + the bundled catalog (build-time, needs network
// once for three.js from the CDN). Reuses the REAL renderThumbs() from the viewer
// (device/creatures/js/setup/fluid-stage.js) in headless Chromium, re-encodes each
// portrait to a small WebP, and writes:
//   src/catalog/thumbs/<cute-id>.webp
//   src/catalog/catalog.json   — {id, name, file} for every cute-kit Molty
// The .molty files themselves come from `node device/creatures/tools/molty-export.mjs all`
// (device/creatures/molty/<name>.molty); this script fails if one is missing.
//
//   node tools/thumbs.mjs [px=112] [quality=0.82]
import { chromium } from 'playwright';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, extname } from 'node:path';

const PX = +(process.argv[2] ?? 112), Q = +(process.argv[3] ?? 0.82);
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const VIEWER = join(ROOT, 'device/creatures');
const MOLTY = join(ROOT, 'device/creatures/molty');
const OUT = fileURLToPath(new URL('../src/catalog/', import.meta.url));
mkdirSync(join(OUT, 'thumbs'), { recursive: true });

const PAGE = `<!doctype html><meta charset="utf-8">
<script type="importmap">{"imports":{"three":"https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.js"}}</script>
<script type="module">
import { renderThumbs, CUTE_CATALOG } from '/js/setup/fluid-stage.js';
const out = [];
renderThumbs(async (id, url) => {
  const img = new Image(); img.src = url; await img.decode();
  const c = document.createElement('canvas'); c.width = c.height = ${PX};
  c.getContext('2d').drawImage(img, 0, 0, ${PX}, ${PX});
  out.push({ id, name: CUTE_CATALOG.find((e) => e.id === id).name, webp: c.toDataURL('image/webp', ${Q}) });
  if (out.length === CUTE_CATALOG.length) window.__done = out;
}, ${Math.ceil(PX / 2)});
</script>`;

const browser = await chromium.launch();
const page = await browser.newPage();
page.on('pageerror', (e) => console.error('pageerror', e.message));
await page.route('http://viewer.local/**', (route) => {
  const p = new URL(route.request().url()).pathname;
  if (p === '/') return route.fulfill({ contentType: 'text/html', body: PAGE });
  const f = join(VIEWER, p);
  if (!existsSync(f)) return route.fulfill({ status: 404, body: '' });
  route.fulfill({ contentType: extname(f) === '.js' ? 'text/javascript' : 'application/octet-stream', body: readFileSync(f) });
});
await page.goto('http://viewer.local/');
const out = await (await page.waitForFunction(() => window.__done, null, { timeout: 120000 })).jsonValue();
await browser.close();

let bytes = 0;
const creatures = out.map(({ id, name, webp }) => {
  const file = id.replace(/^cute-/, '') + '.molty';
  if (!existsSync(join(MOLTY, file))) throw new Error(`missing ${file} — run: node device/creatures/tools/molty-export.mjs all`);
  const buf = Buffer.from(webp.split(',')[1], 'base64');
  bytes += buf.length;
  writeFileSync(join(OUT, 'thumbs', `${id}.webp`), buf);
  return { id, name, file };
});
writeFileSync(join(OUT, 'catalog.json'), JSON.stringify({
  version: 2,
  note: 'Generated by tools/thumbs.mjs from the cute-kit registry. .molty bytes: device/creatures/molty/<file>; thumbnails: thumbs/<id>.webp.',
  creatures,
}, null, 2) + '\n');
console.log(`${creatures.length} thumbs, ${PX}px, ${bytes} B total webp`);
