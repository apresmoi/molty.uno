#!/usr/bin/env bash
# build.sh: Molty's screen for a computer and for the web, from the firmware's own sources (web_molty.c).
#   build.sh host <out dir>   the native player (web_main.c): <out dir>/web_molty
#   build.sh test <out dir> <file.c>   a host test that includes web_molty.c whole: <out dir>/<file>
#   build.sh wasm <out dir>   the WebAssembly module: <out dir>/molty.wasm   (needs emcc, see EMSCRIPTEN below)
#   build.sh deps <out dir>   every file the module is made of, a path a line
#   build.sh emscripten       the pinned toolchain's version
# cJSON comes from ESP-IDF, as for the host tests: set IDF_PATH (default ~/esp/esp-idf).
# Both builds: no fused multiply-adds, no errno from the maths (as main/CMakeLists.txt builds the fluid), so the
# floats round the same way in both. Both are -O2, as the device (the module was -Os: a sixth smaller, and a sixth
# slower where it counts: a slow phone with a wave out on the page, a heading's wide window and the page's field drawing).
# Do not run this by hand for the website: `make web-molty` builds, checks the two against each other and installs.
set -euo pipefail

EMSCRIPTEN="7.0.0"   # the pinned toolchain: brew install emscripten
if [ "${1:-}" = emscripten ]; then echo "$EMSCRIPTEN"; exit 0; fi

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MAIN="$(cd "$HERE/.." && pwd)/main"
IDF_JSON="${IDF_PATH:-$HOME/esp/esp-idf}/components/json/cJSON"
MODE="${1:?host or wasm}"
OUT="${2:?out dir}"
mkdir -p "$OUT"

SRCS=(
  "$HERE/web_molty.c" "$HERE/web_sdk.c" "$HERE/web_field.c"   # web_cat.c below is main/creature/creature_clip.c,
  "$MAIN/fluid/fluid_director.c" "$MAIN/fluid/fluid_ask.c" "$MAIN/fluid/fluid_askview.c" "$HERE/web_sim.c"   # web_sim.c main/fluid/fluid_sim.c
  "$MAIN/fluid/fluid_target.c" "$MAIN/fluid/fluid_draw.c" "$MAIN/fluid/fluid_fine.c" "$MAIN/fluid/glyph_rsvp.c"
  "$MAIN/fluid/glyph_font.c" "$MAIN/fluid/screen_nap.c"
  "$MAIN/creature/cute_spec.c" "$MAIN/creature/cute_rig.c" "$MAIN/creature/mood_engine.c" "$MAIN/creature/rig_geo.c"
  "$MAIN/creature/creature_player.c" "$MAIN/creature/creature_body.c" "$MAIN/creature/creature_pkg.c"
  "$HERE/web_cat.c" "$MAIN/creature/creature_dots.c" "$MAIN/creature/creature_ring.c"
  "$MAIN/pkg/pkg_parse.c" "$MAIN/scene/scene_player.c" "$MAIN/link/link_protocol.c" "$MAIN/sense/gesture.c"
  "$IDF_JSON/cJSON.c"
)
INCS=(-I"$OUT" -I"$HERE/sdk" -I"$MAIN/fluid" -I"$MAIN/creature" -I"$MAIN/scene" -I"$MAIN/pkg" -I"$MAIN/link"
      -I"$MAIN/sense" -I"$MAIN/board" -I"$MAIN/diag" -I"$IDF_JSON")
CFLAGS=(-std=c11 -D_POSIX_C_SOURCE=200809L -D_DARWIN_C_SOURCE -D_DEFAULT_SOURCE -ffp-contract=off -fno-math-errno
        -Wall -Wextra -Werror -Wno-deprecated-declarations)

# the default .molty as the image carries it (main/CMakeLists.txt EMBED_FILES)
{
  echo "/* generated by web/build.sh from main/creature/default.molty: do not edit */"
  echo "const uint8_t _binary_default_molty_start[] = {"
  od -An -v -tu1 "$MAIN/creature/default.molty" | tr -s ' \n' ',' | sed 's/^,//; s/,$//'
  echo "};"
} > "$OUT/web_default_molty.h"

case "$MODE" in
host)
  cc -O2 "${CFLAGS[@]}" "${INCS[@]}" "$HERE/web_main.c" "${SRCS[@]}" -lm -o "$OUT/web_molty"
  ;;
test)
  T="${3:?test file}"
  cc -O2 "${CFLAGS[@]}" "${INCS[@]}" "$T" "${SRCS[@]:1}" -lm -o "$OUT/$(basename "$T" .c)"
  ;;
wasm)
  have="$(emcc --version 2>/dev/null | sed -n '1s/.* \([0-9][0-9.]*\)\(-git\)\{0,1\}$/\1/p')"
  [ "$have" = "$EMSCRIPTEN" ] || { echo "web/build.sh: emscripten $EMSCRIPTEN wanted, '${have:-none}' found (brew install emscripten)" >&2; exit 2; }
  emcc -O2 "${CFLAGS[@]}" "${INCS[@]}" "${SRCS[@]}" \
    --no-entry -sSTANDALONE_WASM=1 -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=16777216 -sSTACK_SIZE=262144 \
    -sMALLOC=emmalloc -sFILESYSTEM=0 -sERROR_ON_UNDEFINED_SYMBOLS=1 \
    -o "$OUT/molty.wasm"
  ;;
deps)
  { cc -MM "${CFLAGS[@]}" "${INCS[@]}" "${SRCS[@]}" | tr -s ' \\\n' '\n' | grep '^/'
    echo "$HERE/build.sh"; echo "$MAIN/creature/default.molty"; } | sort -u
  ;;
*) echo "web/build.sh: host, wasm, deps or emscripten" >&2; exit 2 ;;
esac
