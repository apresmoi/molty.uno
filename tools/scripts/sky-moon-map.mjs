// The always-on moon's face (device/firmware/main/creature/sky.c): the near side of the astrology globe's map
// (skills/molty-astro/assets/maps/moon.png, an equirectangular 128 x 64, its middle column facing us as the globe
// scene shows it) seen straight on, 32 x 32 grey levels 0..15 (0: off the disc), two a byte. 512 bytes.
//   node tools/scripts/sky-moon-map.mjs > device/firmware/main/creature/sky_moon_map.h
import fs from 'node:fs';
import path from 'node:path';
import { readPng } from '../../packages/tools/display/assets.mjs';

const ROOT = path.resolve(import.meta.dirname, '../..');
const map = readPng(fs.readFileSync(path.join(ROOT, 'skills/molty-astro/assets/maps/moon.png')));
const N = 32, SUB = 4;
const grey = (u, v) => {
  const x = Math.min(map.w - 1, Math.floor(u * map.w)), y = Math.min(map.h - 1, Math.max(0, Math.floor(v * map.h)));
  const q = (y * map.w + x) * 4;
  return 0.3 * map.rgba[q] + 0.59 * map.rgba[q + 1] + 0.11 * map.rgba[q + 2];
};
const level = [];
for (let j = 0; j < N; j++) for (let i = 0; i < N; i++) {
  let sum = 0, n = 0;
  for (let b = 0; b < SUB; b++) for (let a = 0; a < SUB; a++) {
    const nx = ((i + (a + 0.5) / SUB) / N) * 2 - 1, ny = 1 - ((j + (b + 0.5) / SUB) / N) * 2, rr = nx * nx + ny * ny;
    if (rr >= 1) continue;
    const nz = Math.sqrt(1 - rr);
    sum += grey(Math.atan2(nx, nz) / (2 * Math.PI) + 0.5, 0.5 - Math.asin(ny) / Math.PI); n++;
  }
  level.push(n * 2 < SUB * SUB ? 0 : Math.max(1, Math.round((sum / n / 255) * 15)));
}
const bytes = [];
for (let k = 0; k < level.length; k += 2) bytes.push(level[k] | (level[k + 1] << 4));
const rows = [];
for (let k = 0; k < bytes.length; k += 16) rows.push('    ' + bytes.slice(k, k + 16).map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
process.stdout.write(`/* generated by tools/scripts/sky-moon-map.mjs from skills/molty-astro/assets/maps/moon.png: do not edit */
/* the moon's near side seen straight on, ${N} x ${N}, grey 0..15 (0: off the disc), two a byte (low nibble first), north up */
#pragma once
#include <stdint.h>
#define SKY_MAP_N ${N}
static const uint8_t SKY_MOON_MAP[${bytes.length}] = {
${rows.join('\n')}
};
`);
